"""Generate image derivatives with existing Pillow/WebP tooling; never alter sources.

Run from the repository root. Pillow is an optional authoring tool, not a build
dependency. PNG artwork/screenshots use lossless WebP; portraits use quality 92.
"""
from pathlib import Path
import hashlib
import json
import re
import sys
import shutil
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
if len(sys.argv) == 3 and sys.argv[1] == "--favicons":
    backup = ROOT / "public/images/original-favicons"
    backup.mkdir(parents=True, exist_ok=True)
    for name in ("favicon.png", "favicon.ico"):
        if not (backup / name).exists():
            shutil.copy2(ROOT / "public" / name, backup / name)
    with Image.open(sys.argv[2]) as image:
        image.resize((32, 32), Image.Resampling.LANCZOS).save(ROOT / "public/favicon.png", optimize=True)
        image.resize((180, 180), Image.Resampling.LANCZOS).save(ROOT / "public/apple-touch-icon.png", optimize=True)
        image.save(ROOT / "public/favicon.ico", sizes=[(16, 16), (32, 32), (48, 48)])
    for name in ("favicon.png", "favicon.ico", "apple-touch-icon.png"):
        with Image.open(ROOT / "public" / name) as image:
            image.load()
            print(f"{name}: {image.format} {image.size}, {(ROOT / 'public' / name).stat().st_size} bytes")
    raise SystemExit(0)
DATA = ROOT / "src/data.ts"
MANIFEST = ROOT / "src/imageAssets.ts"
AUDIT = ROOT / "docs/performance/image-optimization.json"
MARKER = "export const IMAGE_ASSETS: Record<string, ImageAsset> = "

sources = {"/" + p.lstrip("/") for p in re.findall(r"['\"](/?images/[^'\"]+\.(?:png|jpe?g))['\"]", DATA.read_text(encoding="utf-8")) if not p.startswith("/images/optimized/")}
if AUDIT.exists():
    sources.update(json.loads(AUDIT.read_text(encoding="utf-8")).keys())

assets = {}
for source in sorted(sources):
    source_file = ROOT / "public" / source.lstrip("/")
    with Image.open(source_file) as original:
        image = ImageOps.exif_transpose(original)
        image = image.convert("RGBA" if "A" in image.getbands() or "transparency" in original.info else "RGB")
        portrait = "/meet-the-team/" in source or "/pl-advisors/" in source
        avatar_size = 96 if "/meet-the-team/" in source else 112
        lossless = not portrait
        if portrait:
            scales = [min(1, size / min(image.size)) for size in (avatar_size, avatar_size * 2, avatar_size * 3)]
        else:
            widths = (96, 192, image.width) if "/logo/" in source else (480, 960, image.width)
            scales = [min(1, width / image.width) for width in widths]
        variants = []
        for scale in sorted(set(scales)):
            width, height = max(1, round(image.width * scale)), max(1, round(image.height * scale))
            resized = image.resize((width, height), Image.Resampling.LANCZOS) if (width, height) != image.size else image.copy()
            relative = Path(source.removeprefix("/images/")).with_suffix("")
            destination = Path("images/optimized") / relative.parent / f"{relative.name}-{width}.webp"
            output = ROOT / "public" / destination
            output.parent.mkdir(parents=True, exist_ok=True)
            # In lossless mode quality controls encoding effort, not pixel fidelity.
            options = {"lossless": lossless, "quality": 80 if lossless else 92, "method": 4 if lossless else 6, "exact": True}
            if original.info.get("icc_profile"):
                options["icc_profile"] = original.info["icc_profile"]
            resized.save(output, "WEBP", **options)
            with Image.open(output) as decoded:
                assert decoded.size == resized.size
                if lossless:
                    assert decoded.convert(resized.mode).tobytes() == resized.tobytes(), f"Lossless verification failed: {output}"
            variants.append({"src": "/" + destination.as_posix(), "width": width, "height": height, "bytes": output.stat().st_size})
        largest = variants[-1]
        assets[source] = {"src": largest["src"], "width": largest["width"], "height": largest["height"], "originalWidth": image.width, "originalHeight": image.height, "originalBytes": source_file.stat().st_size, "originalSha256": hashlib.sha256(source_file.read_bytes()).hexdigest(), "lossless": lossless, "variants": variants}
        print(f"{source}: {source_file.stat().st_size:,} -> {largest['bytes']:,} bytes ({len(variants)} variants)", flush=True)

AUDIT.parent.mkdir(parents=True, exist_ok=True)
AUDIT.write_text(json.dumps(assets, indent=2) + "\n", encoding="utf-8")
runtime_assets = {source: {key: asset[key] for key in ("src", "width", "height")} | {"variants": [{key: variant[key] for key in ("src", "width", "height")} for variant in asset["variants"]]} for source, asset in assets.items()}
MANIFEST.write_text("// Generated by scripts/optimize-images.py. Keep original assets.\n"
    "export interface ImageVariant { src: string; width: number; height: number; }\n"
    "export interface ImageAsset { src: string; width: number; height: number; variants: ImageVariant[]; }\n"
    + MARKER + json.dumps(runtime_assets, indent=2) + ";\n", encoding="utf-8")
text = DATA.read_text(encoding="utf-8")
for source, asset in assets.items():
    for old in (source, source.lstrip("/")):
        text = text.replace("'" + old + "'", "'" + asset["src"] + "'")
DATA.write_text(text, encoding="utf-8", newline="\n")
print(f"Generated {sum(len(a['variants']) for a in assets.values())} WebP files for {len(assets)} source images.")
